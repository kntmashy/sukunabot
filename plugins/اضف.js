export default {
  name: 'أضف',
  aliases: ['add', 'اضف'],
  tags: ['group'],
  help: ['أضف [رقم]'],

  groupOnly:        true,   // جروب فقط
  ownerOnly:        true,   // المطور فقط
  botAdminRequired: true,   // البوت لازم يكون أدمن

  async execute(conn, m, { text, args }) {
    // ── فحص المطور ────────────────────────────────────
    const devNumbers = ['201036547166', '201016855501']
    const senderNum  = m.sender.replace('@s.whatsapp.net', '').replace(/\D/g, '')
    if (!devNumbers.includes(senderNum)) {
      return m.reply(
        `*╮═≼『⛩️┃تنبيه┃⛩️』≽═╭*\n` +
        `*┇⌗╎ꕥ هذا الأمر للمطور فقط ⌗*\n` +
        `*╯✯≼══━━﹂⛩️﹁━━══≽✯*`
      )
    }

    // ── استخرج الرقم ──────────────────────────────────
    // يقبل: 201012345678 أو 0201012345678 أو +201012345678
    const raw = (text || args[0] || '').trim()
    const num = raw.replace(/\D/g, '')          // شيل أي حرف مش رقم

    if (!num || num.length < 7) {
      return m.reply(
        `*╮═≼『⛩️┃تنبيه┃⛩️』≽═╭*\n` +
        `*┇⌗╎ꕥ اكتب رقم صحيح بعد الأمر ⌗*\n` +
        `*┇⌗╎ꕥ مثال: .أضف 201012345678 ⌗*\n` +
        `*╯✯≼══━━﹂⛩️﹁━━══≽✯*`
      )
    }

    const jid = `${num}@s.whatsapp.net`

    try {
      const res = await conn.groupParticipantsUpdate(m.chat, [jid], 'add')
      const status = res?.[0]?.status

      // ── ردود حسب نتيجة الإضافة ────────────────────
      if (status === 200) {
        return m.reply(
          `*╮═≼『⛩️┃نجاح┃⛩️』≽═╭*\n` +
          `*┇⌗╎✅ تم إضافة +${num} للجروب بنجاح! ⌗*\n` +
          `*╯✯≼══━━﹂⛩️﹁━━══≽✯*`
        )
      }

      if (status === 403) {
        return m.reply(
          `*╮═≼『⛩️┃تنبيه┃⛩️』≽═╭*\n` +
          `*┇⌗╎❌ الشخص ده أوقف إضافته للجروبات ⌗*\n` +
          `*╯✯≼══━━﹂⛩️﹁━━══≽✯*`
        )
      }

      if (status === 408) {
        return m.reply(
          `*╮═≼『⛩️┃تنبيه┃⛩️』≽═╭*\n` +
          `*┇⌗╎❌ الرقم مش موجود على واتساب ⌗*\n` +
          `*╯✯≼══━━﹂⛩️﹁━━══≽✯*`
        )
      }

      if (status === 409) {
        return m.reply(
          `*╮═≼『⛩️┃تنبيه┃⛩️』≽═╭*\n` +
          `*┇⌗╎⚠️ الشخص ده موجود في الجروب أصلاً ⌗*\n` +
          `*╯✯≼══━━﹂⛩️﹁━━══≽✯*`
        )
      }

      // أي كود تاني
      return m.reply(
        `*╮═≼『⛩️┃تنبيه┃⛩️』≽═╭*\n` +
        `*┇⌗╎⚠️ حصل مشكلة — كود: ${status} ⌗*\n` +
        `*╯✯≼══━━﹂⛩️﹁━━══≽✯*`
      )

    } catch (e) {
      return m.reply(
        `*╮═≼『⛩️┃خطأ┃⛩️』≽═╭*\n` +
        `*┇⌗╎❌ فشل الأمر: ${e.message} ⌗*\n` +
        `*╯✯≼══━━﹂⛩️﹁━━══≽✯*`
      )
    }
  }
}