const decorateTitle = (t) => `『 ${t} 』`;
const withCredit = (text) => `${text}${FOOTER}`;

const TEAM_BUDGET = 200_000_000;
const SQUAD_SIZE = 11;
const MIN_INCREMENT = 500_000;
const MIN_RESERVE_PER_SLOT = 1_000_000;
