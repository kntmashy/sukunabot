// ================== الـ handler المحصّن ==================
const lastJudgmentByChat = new Map();

const handler = async (m) => {
  try {
    if (!Array.isArray(allJudgments) || allJudgments.length === 0) {
      return m.reply(withCredit('⚠️ بنك الأحكام فاضي حالياً، حاول تاني بعدين.'));
    }

    const chatId = m.chat;
    const lastJudgment = lastJudgmentByChat.get(chatId);

    let randomJudgment;
    if (allJudgments.length === 1) {
      randomJudgment = allJudgments[0];
    } else {
      do {
        randomJudgment = allJudgments[Math.floor(Math.random() * allJudgments.length)];
      } while (randomJudgment === lastJudgment);
    }

    lastJudgmentByChat.set(chatId, randomJudgment);

    const title = 'مستشفى الأحكام - النسخة الشريرة';
    const response =
      `${decorateTitle(title)}\n\n` +
      `يا بطل، الحكم اللي طلعلك هو:\n\n` +
      `🔥 ${randomJudgment}\n\n` +
      `نفذ بسرعة وبدون تهرب! ⚔️`;

    return await m.reply(withCredit(response));
  } catch (err) {
    console.error('خطأ في أمر الأحكام:', err);
    return m.reply('❌ حصل خطأ غير متوقع، حاول تاني.');
  }
};

handler.help = ['احكام - يبعتلك حكم عشوائي شرير لازم تنفذه'];
handler.tags = ['fun'];
handler.command = /^احكام$/i;

export default handler;