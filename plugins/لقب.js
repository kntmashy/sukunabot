// ════════════════════════════════════════════
// أمر .لقبي — تسجيل لقب المستخدم
// ════════════════════════════════════════════
let handler = async (m, { conn, text }) => {
  const user = global.db.data.users[m.sender]
  if (!user) return m.reply('*┇⌗╎حدث خطأ، حاول مرة أخرى*')

  if (!text) {
    const current = user.title || 'لا يوجد لقب'
    return m.reply(
      `*╔═══━━━─── • ───━━━═══╗*\n` +
      `*   ⟡ 𓂀 𝗟𝗤𝗔𝗕 𓂀 ⟡*\n` +
      `*╚═══━━━─── • ───━━━═══╝*\n` +
      `*┇⌗╎👑 لقبك الحالي:* ${current}\n` +
      `*┇⌗╎اكتب .لقبي (اللقب) لتغييره*\n` +
      `*╯✯≼══━━﹂⛩️﹁━━══≽✯*`
    )
  }

  if (text.length > 30)
    return m.reply(
      `*╮═≼『⛩️┃تنبيه┃⛩️』≽═╭*\n` +
      `*┇⌗╎اللقب طويل جداً — الحد الأقصى 30 حرف*\n` +
      `*╯✯≼══━━﹂⛩️﹁━━══≽✯*`
    )

  user.title = text

  await m.reply(
    `*╔═══━━━─── • ───━━━═══╗*\n` +
    `*   ⟡ 𓂀 𝗟𝗤𝗔𝗕 𓂀 ⟡*\n` +
    `*╚═══━━━─── • ───━━━═══╝*\n` +
    `*┇⌗╎👑 تم تسجيل لقبك بنجاح*\n` +
    `*┇⌗╎🏷️ لقبك:* ${text}\n` +
    `*╯✯≼══━━﹂⛩️﹁━━══≽✯*`
  )
}

handler.help    = ['لقبي <اللقب>']
handler.tags    = ['economy']
handler.command = ['لقبي', 'لقب']
export default handler